use crate::util::exclude;
use crate::{
    config::{Config, DropTiming},
    expr::expand_block,
    util::{add_generic, assert_not_async, assert_not_const, rewrite_output},
};
use proc_macro2::TokenStream;
use quote::ToTokens;
use syn::Ident;
use syn::{ItemFn, Result, Signature, parse_quote};

pub fn expand(config: Config, func: ItemFn) -> Result<TokenStream> {
    expand_fn(&config, func, true).map(ToTokens::into_token_stream)
}

pub fn expand_fn_from(config: &Config, mut func: ItemFn) -> Result<ItemFn> {
    if exclude(&mut func.attrs) {
        Ok(func)
    } else {
        expand_fn(config, func, false)
    }
}

fn expand_fn(config: &Config, mut func: ItemFn, redefine_c: bool) -> Result<ItemFn> {
    // bug: accept the color generated by caller...
    let color_generic = config
        .color
        .get_or_create_generic_color(&func.sig.generics)?;

    validate_generic_signature(&func.sig)?;
    core::assert_matches!(config.drop_timing, DropTiming::Relaxed);

    let emit = expand_block(*func.block, config, &parse_quote!(#color_generic), true)?;

    func.sig = rewrite_signature(
        func.sig,
        &config.crate_path,
        color_generic,
        config.autocomplete,
        redefine_c,
    );

    func.block = Box::new(emit);

    Ok(func)
}

pub fn rewrite_signature(
    mut sig: Signature,
    crate_path: &syn::Path,
    color_generic: Ident,
    use_autocomplete: bool,
    redefine_c: bool,
) -> Signature {
    if redefine_c {
        sig.generics = add_generic(sig.generics, crate_path, &color_generic);
    }

    sig.output = rewrite_output(
        sig.output,
        crate_path,
        &parse_quote!(#color_generic),
        use_autocomplete,
    );
    sig
}

// just a light check for better diagnosis... rustc would catch these anyway
pub fn validate_generic_signature(sig: &Signature) -> syn::Result<()> {
    assert_not_async(sig)?;
    assert_not_const(sig)
}
