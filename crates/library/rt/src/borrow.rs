//! Linear borrow, pinning, and erasure primitives emitted during lowering.

use colorless_core::callbacks::FlatBorrowScope;
use colorless_core::{BorrowScope, Colored, callbacks::ColoredCallOnce};
use core::marker::PhantomData;
use core::ptr::NonNull;

/// Type-erased borrow carrier across continuation scopes.
///
/// # Safety boundary
///
/// Implements `Send` and `Sync` requiring only `T: Send`. Manual construction
/// or use is unsound. Inert validation checks source borrowing, while generated
/// code must additionally keep the owner stable, execute linearly, and consume
/// this token at most once. See `SAFETY.md`.
#[doc(hidden)]
#[repr(transparent)]
pub struct ErasedBorrow<T: ?Sized>(NonNull<T>, PhantomData<*mut T>);

/// A transparent cell used internally by `borrow!` and `reborrow!`.
///
/// # Safety boundary
///
/// This hidden type is emitted only by the `#[colorless]` compiler. It is not
/// a supported hand-written API, even though macro expansion makes it public.
///
/// `LocalCell<T>` implements `Sync` solely requiring `T: Send`. In general Rust
/// code, sharing an `UnsafeCell` across threads without synchronization is unsound.
/// Here, soundness relies entirely on the synthetic **inert code** emitted by `#[colorless]`:
/// 1. The inert code mirrors the linear evaluation sequence and is subjected to standard
///    `rustc` borrow and lifetime checking.
/// 2. Borrowck statically verifies that references are strictly exclusive (`&mut`),
///    non-aliasing, and respect valid lifetimes.
/// 3. Colorless code generation guarantees single-shot sequential progression—never
///    concurrent evaluation.
///
/// The inert program is necessary evidence for that argument, but it is not
/// sufficient on its own; the complete code-generation obligations live in
/// `SAFETY.md` at the repository root.
#[doc(hidden)]
#[repr(transparent)]
pub struct LocalCell<'a, T: ?Sized>(pub(super) NonNull<T>, PhantomData<&'a mut T>);

/// Owns a local while it has a compiler-controlled stable address.
///
/// Dropping this guard drops the local unless [`ErasedBorrow::unpin`] has
/// transferred ownership out of it. This is hidden because only generated
/// code may establish the required stable-storage protocol.
#[doc(hidden)]
#[repr(transparent)]
pub struct MaybeUnpinned<'a, T> {
    value: Option<T>,
    _marker: PhantomData<&'a T>,
}

#[doc(hidden)]
pub trait Reborrow<'a> {
    type Target: ?Sized;

    #[doc(hidden)]
    unsafe fn reborrow(&self) -> &'a mut Self::Target;
}

/// Wrapper adapting a closure into a [`BorrowScope`] state machine with a `Usage` continuation.
#[doc(hidden)]
pub struct UnsafeFnScope<F>(F);

// Safety: Unsafe outside the macro; checked by the synthetic inert code.
unsafe impl<T: Send + ?Sized> Send for ErasedBorrow<T> {}

// Safety: Unsafe outside the macro; checked by the synthetic inert code.
unsafe impl<T: Send + ?Sized> Sync for ErasedBorrow<T> {}

// Safety: Soundness relies strictly on the synthetic inert code generated by
// #[colorless], which undergoes borrow-checking to guarantee linear, non-concurrent,
// exclusive access. Manual use outside macro expansions is unsound.
unsafe impl<T: Send + ?Sized> Send for LocalCell<'_, T> {}

// Safety: Soundness relies strictly on the inert code proving exclusive linear access.
unsafe impl<T: Send + ?Sized> Sync for LocalCell<'_, T> {}

impl<T: ?Sized> ErasedBorrow<T> {
    /// Converts this erased borrow token into a mutable cell wrapper.
    ///
    /// # Safety
    ///
    /// The caller must ensure that the underlying target remains valid and pinned for `'a`,
    /// and that no conflicting aliasing borrows of the target coexist.
    #[inline(always)]
    pub unsafe fn into_mut<'a>(mut self) -> LocalCell<'a, T> {
        LocalCell::new(unsafe { self.0.as_mut() })
    }
}

impl<'a, T> Reborrow<'a> for ErasedBorrow<MaybeUnpinned<'a, T>> {
    type Target = T;

    #[inline(always)]
    unsafe fn reborrow(&self) -> &'a mut T {
        unsafe { (*self.0.as_ptr()).value.as_mut().unwrap_unchecked() }
    }
}

#[doc(hidden)]
impl<T> ErasedBorrow<MaybeUnpinned<'_, T>> {
    /// Transfers ownership out of the guard.
    ///
    /// # Safety
    ///
    /// Every reference produced from this token must be dead before this call.
    /// The token must be consumed exactly once, and generated code must not
    /// access the old stable address after the returned `T` is moved. The
    /// consuming receiver prevents ordinary safe-code double use, but branch
    /// joins still need compiler proof of exactly one transfer per path.
    #[inline(always)]
    pub unsafe fn unpin(mut self) -> T {
        unsafe { self.0.as_mut().value.take().unwrap_unchecked() }
    }
}
