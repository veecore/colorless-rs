impl<'a, T: ?Sized> LocalCell<'a, T> {
    #[inline(always)]
    pub fn new(value: &'a mut T) -> Self {
        Self(NonNull::from_mut(value), PhantomData)
    }

    /// Consumes this cell and returns the underlying mutable reference.
    ///
    /// # Safety
    ///
    /// The caller must ensure that no outstanding borrows derived from this cell are active.
    #[inline(always)]
    pub unsafe fn into_inner(mut self) -> &'a mut T {
        unsafe { self.0.as_mut() }
    }
}

impl<'a, T: ?Sized> Reborrow<'a> for LocalCell<'a, T> {
    type Target = T;
    #[inline(always)]
    unsafe fn reborrow(&self) -> &'a mut T {
        unsafe { &mut *self.0.as_ptr() }
    }
}

#[doc(hidden)]
impl<T> MaybeUnpinned<'_, T> {
    /// Creates an armed ownership guard.
    ///
    /// Constructing the guard is safe: it owns `t` and drops it normally
    /// unless generated code later transfers ownership with
    /// [`ErasedBorrow::unpin`].
    #[inline(always)]
    pub fn new(t: T) -> Self {
        Self {
            value: Some(t),
            _marker: PhantomData,
        }
    }
}

#[doc(hidden)]
impl<C, O, F> BorrowScope<C, O> for UnsafeFnScope<F>
where
    F: ColoredCallOnce<C, ErasedBorrow<O>>,
{
    type Resume = F::Value;

    #[inline(always)]
    fn resume_mut(self, var: &mut O) -> impl Colored<C, Output = Self::Resume> {
        self.0(ErasedBorrow(NonNull::from_mut(var), PhantomData))
    }
}

#[doc(hidden)]
impl<C, O, F> FlatBorrowScope<C, O> for UnsafeFnScope<F>
where
    F: ColoredCallOnce<C, ErasedBorrow<O>>,
{
    type Resume = F::Value;
    type Flow = F::Flow;

    #[inline(always)]
    fn resume_mut_flat(self, var: &mut O) -> Self::Flow {
        self.0(ErasedBorrow(NonNull::from_mut(var), PhantomData))
    }
}

#[doc(hidden)]
#[inline(always)]
pub fn retrieve_type<T>(
    t: ErasedBorrow<MaybeUnpinned<T>>,
    _m: PhantomData<T>,
) -> ErasedBorrow<MaybeUnpinned<T>> {
    t
}

#[doc(hidden)]
#[inline(always)]
pub fn retrieve_type_unpinned<T>(t: ErasedBorrow<T>, _m: PhantomData<T>) -> ErasedBorrow<T> {
    t
}

/// Adapts a closure accepting a [`ErasedBorrow`] into a [`UnsafeFnScope`].
#[inline(always)]
#[doc(hidden)]
pub fn scope_fn<C, O, F>(f: F) -> UnsafeFnScope<F>
where
    UnsafeFnScope<F>: BorrowScope<C, O>,
{
    UnsafeFnScope(f)
}

#[doc(hidden)]
#[inline(always)]
pub fn store_type<T>(_t: &T) -> PhantomData<T> {
    PhantomData
}

#[doc(hidden)]
#[inline(always)]
pub fn __unpin<T>(_val: &mut T) -> T {
    // Only used in inert typecheck branches, never executed
    unsafe { core::hint::unreachable_unchecked() }
}

// Local borrow macros
#[macro_export]
macro_rules! borrow {
    ($ident:ident as $bind:ident) => {
        #[allow(unused_mut)]
        let mut $bind = $crate::__compiler::LocalCell::new($ident);
    };
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = $crate::__compiler::LocalCell::new($ident);
        )*
    };
}

#[macro_export]
macro_rules! rb {
    ($ident:ident) => {{ unsafe { $crate::__compiler::Reborrow::reborrow(&$ident) } }};
}

#[macro_export]
macro_rules! unborrow {
    ($($ident:ident),*) => {
        $(
            let $ident = unsafe { $crate::__compiler::LocalCell::into_inner($ident) };
        )*
    };
}

#[macro_export]
macro_rules! __borrow {
    ($($ident:ident),*) => {};
    ($ident:ident as $bind:ident) => {
        let mut $bind = $ident;
    };
}

#[macro_export]
macro_rules! __rb {
    ($ident:ident) => {
        $ident
    };
}

#[macro_export]
macro_rules! __rbv {
    ($ident:ident) => {
        &mut $ident
    };
}

#[macro_export]
macro_rules! __unborrow {
    ($($ident:ident),*) => {};
}

#[macro_export]
macro_rules! __pin {
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = &mut $ident;
        )*
    };
}

#[macro_export]
macro_rules! __unpin {
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = $crate::__compiler::__unpin($ident);
        )*
    };
}

#[cfg(test)]
mod tests {
    use super::*;
    use colorless_core::test_util::{block_on_test, poll_once};
    use colorless_core::*;
    use std::panic::{AssertUnwindSafe, catch_unwind};
    use std::string::String;
    use std::sync::Arc;
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::task::Poll;

    struct DropProbe {
        drops: Arc<AtomicUsize>,
        panic_on_drop: bool,
    }

    impl DropProbe {
        fn new(drops: Arc<AtomicUsize>) -> Self {
            Self {
                drops,
                panic_on_drop: false,
            }
        }

        fn panicking(drops: Arc<AtomicUsize>) -> Self {
            Self {
                drops,
                panic_on_drop: true,
            }
        }
    }

    impl Drop for DropProbe {
        fn drop(&mut self) {
            self.drops.fetch_add(1, Ordering::SeqCst);
            assert!(!self.panic_on_drop, "probe destructor panicked");
        }
    }

    fn erased<'a, T>(owner: &mut MaybeUnpinned<'a, T>) -> ErasedBorrow<MaybeUnpinned<'a, T>> {
        ErasedBorrow(NonNull::from(owner), PhantomData)
    }

    #[test]
    fn maybe_unpinned_drops_an_armed_owner_once() {
        let drops = Arc::new(AtomicUsize::new(0));

        drop(MaybeUnpinned::new(DropProbe::new(drops.clone())));

        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn unpin_transfers_the_only_drop_obligation() {
        let drops = Arc::new(AtomicUsize::new(0));
        let mut owner = MaybeUnpinned::new(DropProbe::new(drops.clone()));

        let value = unsafe { erased(&mut owner).unpin() };
        drop(owner);
        assert_eq!(drops.load(Ordering::SeqCst), 0);

        drop(value);
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn mutable_access_precedes_ownership_transfer() {
        let mut owner = MaybeUnpinned::new(String::from("initial"));
        let token = erased(&mut owner);

        unsafe { token.reborrow() }.push_str(" value");
        let value = unsafe { token.unpin() };

        assert_eq!(value, "initial value");
    }

    #[test]
    fn both_conditional_transfer_paths_drop_once() {
        for transfer in [false, true] {
            let drops = Arc::new(AtomicUsize::new(0));
            let mut owner = MaybeUnpinned::new(DropProbe::new(drops.clone()));

            let transferred = if transfer {
                Some(unsafe { erased(&mut owner).unpin() })
            } else {
                None
            };

            drop(transferred);
            drop(owner);
            assert_eq!(drops.load(Ordering::SeqCst), 1, "transfer={transfer}");
        }
    }

    #[test]
    fn armed_owner_is_cleaned_up_during_unwind() {
        let drops = Arc::new(AtomicUsize::new(0));
        let result = catch_unwind(AssertUnwindSafe({
            let drops = drops.clone();
            move || {
                let _owner = MaybeUnpinned::new(DropProbe::new(drops));
                panic!("stage panicked before ownership transfer");
            }
        }));

        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn panicking_inner_destructor_is_not_run_twice() {
        let drops = Arc::new(AtomicUsize::new(0));
        let result = catch_unwind(AssertUnwindSafe({
            let drops = drops.clone();
            move || drop(MaybeUnpinned::new(DropProbe::panicking(drops)))
        }));

        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn pending_async_borrow_cancellation_drops_the_armed_owner() {
        let drops = Arc::new(AtomicUsize::new(0));
        let computation = Async::borrow(
            MaybeUnpinned::new(DropProbe::new(drops.clone())),
            scope_fn::<Async, MaybeUnpinned<DropProbe>, _>(move |token| {
                let _ = unsafe { token.reborrow() };
                <core::future::Pending<()> as Colorize<Async>>::colorize(core::future::pending())
            }),
        );
        {
            let mut future = core::pin::pin!(computation.async_());
            assert!(matches!(poll_once(future.as_mut()), Poll::Pending));
        }

        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn completed_async_borrow_drops_the_armed_owner() {
        let drops = Arc::new(AtomicUsize::new(0));
        let computation = Async::borrow(
            MaybeUnpinned::new(DropProbe::new(drops.clone())),
            scope_fn::<Async, MaybeUnpinned<DropProbe>, _>(|token| {
                let _ = unsafe { token.reborrow() };
                Async::ready(())
            }),
        );

        assert_eq!(block_on_test(computation.async_()), ());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn borrow_flat_resume_panic_drops_local() {
        use colorless_core::LocalBorrow;
        let drops = Arc::new(AtomicUsize::new(0));
        let probe = DropProbe::new(drops.clone());
        let result = catch_unwind(AssertUnwindSafe(|| {
            let computation = Async::borrow_flat(
                probe,
                scope_fn::<Async, DropProbe, _>(|_| {
                    panic!("resume panic");
                    #[allow(unreachable_code)]
                    Async::ready(())
                }),
            );
            let mut future = core::pin::pin!(computation.async_());
            let _ = poll_once(future.as_mut());
        }));
        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn borrow_flat_poll_panic_drops_local() {
        use colorless_core::LocalBorrow;
        let drops = Arc::new(AtomicUsize::new(0));
        let probe = DropProbe::new(drops.clone());
        let result = catch_unwind(AssertUnwindSafe(|| {
            let computation = Async::borrow_flat(
                probe,
                scope_fn::<Async, DropProbe, _>(|_| Async::wrap(|| panic!("poll panic"))),
            );
            let mut future = core::pin::pin!(computation.async_());
            let _ = poll_once(future.as_mut());
        }));
        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn test_borrow_mut_reborrow_end() {
        let mut a = String::from("hello");
        let a = &mut a;
        borrow!(a);
        rb!(a).push_str(" world");
        unborrow!(a);
        assert_eq!(a, "hello world");
    }

    #[test]
    fn test_borrow_inert_macros() {
        let a = String::from("inert");
        __borrow!(a);
        let b = __rb!(a);
        __unborrow!(b);
        assert_eq!(b, "inert");
    }

    #[test]
    fn test_pin_inert_macro() {
        let mut a = String::from("pinned");
        __pin!(a);
        a.push_str("_mut");
        assert_eq!(*a, "pinned_mut");
    }
}
