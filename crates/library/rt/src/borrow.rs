//! Linear borrow, pinning, and erasure primitives emitted during lowering.

use core::cell::UnsafeCell;
use core::marker::PhantomData;
use core::mem::ManuallyDrop;
use core::ptr::NonNull;

use colorless_core::callbacks::ColoredCallOnce;
use colorless_core::{BorrowScope, Colored};

/// A transparent cell used internally by `borrow_mut!` and `reborrow!`.
///
/// # Safety boundary
///
/// This hidden type is emitted only by the `#[colorless]` compiler. It is not
/// a supported hand-written API, even though macro expansion makes it public.
///
/// `LocalCell<T>` implements `Sync` solely requiring `T: Send`. In general Rust
/// code, sharing an `UnsafeCell` across threads without synchronization is unsound.
/// Here, soundness relies entirely on the synthetic **inert code** emitted by `#[colorless]`:
/// 1. The inert code mirrors the linear evaluation sequence and is subjected to standard
///    `rustc` borrow and lifetime checking.
/// 2. Borrowck statically verifies that references are strictly exclusive (`&mut`),
///    non-aliasing, and respect valid lifetimes.
/// 3. Colorless code generation guarantees single-shot sequential progression—never
///    concurrent evaluation.
///
/// The inert program is necessary evidence for that argument, but it is not
/// sufficient on its own; the complete code-generation obligations live in
/// `SAFETY.md` at the repository root.
#[repr(transparent)]
#[doc(hidden)]
pub struct LocalCell<T>(pub UnsafeCell<T>);

/// Owns a local while it has a compiler-controlled stable address.
///
/// Dropping this guard drops the local unless [`ErasedBorrow::unpin`] has
/// transferred ownership out of it. This is hidden because only generated
/// code may establish the required stable-storage protocol.
#[doc(hidden)]
pub struct MaybeUnpinned<T> {
    // todo: just use option
    value: ManuallyDrop<T>,
    unpinned: bool,
}

/// Type-erased borrow carrier across continuation scopes.
///
/// # Safety boundary
///
/// Implements `Send` and `Sync` requiring only `T: Send`. Manual construction
/// or use is unsound. Inert validation checks source borrowing, while generated
/// code must additionally keep the owner stable, execute linearly, and consume
/// this token at most once. See `SAFETY.md`.
#[repr(transparent)]
#[doc(hidden)]
pub struct ErasedBorrow<T>(NonNull<T>, PhantomData<*mut T>);

/// Wrapper adapting a closure into a [`BorrowScope`] state machine with a `Usage` continuation.
#[doc(hidden)]
pub struct UnsafeFnScope<F>(F);

// Safety: Soundness relies strictly on the synthetic inert code generated by
// #[colorless], which undergoes borrow-checking to guarantee linear, non-concurrent,
// exclusive access. Manual use outside macro expansions is unsound.
unsafe impl<T: Send> Send for LocalCell<T> {}

// Safety: Soundness relies strictly on the inert code proving exclusive linear access.
unsafe impl<T: Send> Sync for LocalCell<T> {}

// Safety: Unsafe outside the macro; checked by the synthetic inert code.
unsafe impl<T: Send> Send for ErasedBorrow<T> {}

// Safety: Unsafe outside the macro; checked by the synthetic inert code.
unsafe impl<T: Send> Sync for ErasedBorrow<T> {}

#[doc(hidden)]
impl<T> MaybeUnpinned<T> {
    /// Creates an armed ownership guard.
    ///
    /// Constructing the guard is safe: it owns `t` and drops it normally
    /// unless generated code later transfers ownership with
    /// [`ErasedBorrow::unpin`].
    #[inline(always)]
    pub fn new(t: T) -> Self {
        Self {
            value: ManuallyDrop::new(t),
            unpinned: false,
        }
    }
}

#[doc(hidden)]
impl<T> ErasedBorrow<MaybeUnpinned<T>> {
    /// Reborrows the guarded local for generated stage code.
    ///
    /// # Safety
    ///
    /// The `MaybeUnpinned<T>` owner must still be alive at the address behind
    /// this token, the returned reference must not outlive that owner or cross
    /// a generated ownership transfer, and no aliased mutable reference may
    /// exist. Only compiler-emitted code satisfying inert validation and the
    /// `SAFETY.md` protocol may call this.
    #[inline(always)]
    pub unsafe fn as_mut<'a>(&mut self) -> &'a mut T {
        unsafe { &mut self.0.as_mut().value }
    }

    /// Transfers ownership out of the guard.
    ///
    /// # Safety
    ///
    /// Every reference produced from this token must be dead before this call.
    /// The token must be consumed exactly once, and generated code must not
    /// access the old stable address after the returned `T` is moved. The
    /// consuming receiver prevents ordinary safe-code double use, but branch
    /// joins still need compiler proof of exactly one transfer per path.
    #[inline(always)]
    pub unsafe fn unpin(mut self) -> T {
        let shared_ptr = unsafe { self.0.as_mut() };
        shared_ptr.unpinned = true;
        unsafe { ManuallyDrop::take(&mut shared_ptr.value) }
    }
}

impl<T> Drop for MaybeUnpinned<T> {
    fn drop(&mut self) {
        if !self.unpinned {
            unsafe {
                ManuallyDrop::drop(&mut self.value);
            }
        }
    }
}

#[doc(hidden)]
impl<C, O, F> BorrowScope<C, O> for UnsafeFnScope<F>
where
    F: ColoredCallOnce<C, ErasedBorrow<O>>,
{
    type Resume = F::Value;

    #[inline(always)]
    fn resume_mut(self, var: &mut O) -> impl Colored<C, Output = Self::Resume> {
        self.0(ErasedBorrow(NonNull::from_mut(var), PhantomData))
    }
}

/// Adapts a closure accepting a [`ErasedBorrow`] into a [`UnsafeFnScope`].
#[inline(always)]
#[doc(hidden)]
pub fn scope_fn<C, O, F>(f: F) -> UnsafeFnScope<F>
where
    UnsafeFnScope<F>: BorrowScope<C, O>,
{
    UnsafeFnScope(f)
}

#[doc(hidden)]
#[inline(always)]
pub fn store_type<T>(_t: &T) -> PhantomData<T> {
    PhantomData
}

#[doc(hidden)]
#[inline(always)]
pub fn retrieve_type<T>(
    t: ErasedBorrow<MaybeUnpinned<T>>,
    _m: PhantomData<T>,
) -> ErasedBorrow<MaybeUnpinned<T>> {
    t
}

#[doc(hidden)]
#[inline(always)]
pub fn inert_unpin<T>(_val: &mut T) -> T {
    // Only used in inert typecheck branches, never executed
    unsafe { core::hint::unreachable_unchecked() }
}

// Local borrow macros
#[macro_export]
macro_rules! borrow_mut {
    ($ident:ident as $bind:ident) => {
        #[allow(unused_mut)]
        let mut $bind = $crate::__compiler::LocalCell(::core::cell::UnsafeCell::new($ident));
    };
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = $crate::__compiler::LocalCell(::core::cell::UnsafeCell::new($ident));
        )*
    };
}

#[macro_export]
macro_rules! reborrow {
    ($ident:ident) => {{
        (match $ident {
            $crate::__compiler::LocalCell(ref cell) => unsafe {
                &mut *::core::cell::UnsafeCell::get(cell)
            },
        })
    }};
}

#[macro_export]
macro_rules! end_borrow_mut {
    ($($ident:ident),*) => {
        $(
            let $ident = match $ident {
                $crate::__compiler::LocalCell(cell) => {
                    ::core::cell::UnsafeCell::into_inner(cell)
                }
            };
        )*
    };
}

#[macro_export]
macro_rules! borrow_mut_inert {
    ($($ident:ident),*) => {};
    ($ident:ident as $bind:ident) => {
        let mut $bind = $ident;
    };
}

#[macro_export]
macro_rules! reborrow_inert {
    ($ident:ident) => {
        $ident
    };
}

#[macro_export]
macro_rules! end_borrow_mut_inert {
    ($($ident:ident),*) => {};
}

#[macro_export]
macro_rules! pin_local {
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = &mut $ident;
        )*
    };
}

#[macro_export]
macro_rules! unpin_local {
    ($($ident:ident),*) => {
        $(
            #[allow(unused_mut)]
            let mut $ident = $crate::__compiler::inert_unpin($ident);
        )*
    };
}

#[cfg(test)]
mod tests {
    use super::*;
    use colorless_core::test_util::{block_on_test, poll_once};
    use colorless_core::*;
    use std::panic::{AssertUnwindSafe, catch_unwind};
    use std::string::String;
    use std::sync::Arc;
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::task::Poll;

    struct DropProbe {
        drops: Arc<AtomicUsize>,
        panic_on_drop: bool,
    }

    impl DropProbe {
        fn new(drops: Arc<AtomicUsize>) -> Self {
            Self {
                drops,
                panic_on_drop: false,
            }
        }

        fn panicking(drops: Arc<AtomicUsize>) -> Self {
            Self {
                drops,
                panic_on_drop: true,
            }
        }
    }

    impl Drop for DropProbe {
        fn drop(&mut self) {
            self.drops.fetch_add(1, Ordering::SeqCst);
            assert!(!self.panic_on_drop, "probe destructor panicked");
        }
    }

    fn erased<T>(owner: &mut MaybeUnpinned<T>) -> ErasedBorrow<MaybeUnpinned<T>> {
        ErasedBorrow(NonNull::from(owner), PhantomData)
    }

    #[test]
    fn maybe_unpinned_drops_an_armed_owner_once() {
        let drops = Arc::new(AtomicUsize::new(0));

        drop(MaybeUnpinned::new(DropProbe::new(drops.clone())));

        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn unpin_transfers_the_only_drop_obligation() {
        let drops = Arc::new(AtomicUsize::new(0));
        let mut owner = MaybeUnpinned::new(DropProbe::new(drops.clone()));

        let value = unsafe { erased(&mut owner).unpin() };
        drop(owner);
        assert_eq!(drops.load(Ordering::SeqCst), 0);

        drop(value);
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn mutable_access_precedes_ownership_transfer() {
        let mut owner = MaybeUnpinned::new(String::from("initial"));
        let mut token = erased(&mut owner);

        unsafe { token.as_mut() }.push_str(" value");
        let value = unsafe { token.unpin() };

        assert_eq!(value, "initial value");
    }

    #[test]
    fn both_conditional_transfer_paths_drop_once() {
        for transfer in [false, true] {
            let drops = Arc::new(AtomicUsize::new(0));
            let mut owner = MaybeUnpinned::new(DropProbe::new(drops.clone()));

            let transferred = if transfer {
                Some(unsafe { erased(&mut owner).unpin() })
            } else {
                None
            };

            drop(transferred);
            drop(owner);
            assert_eq!(drops.load(Ordering::SeqCst), 1, "transfer={transfer}");
        }
    }

    #[test]
    fn armed_owner_is_cleaned_up_during_unwind() {
        let drops = Arc::new(AtomicUsize::new(0));
        let result = catch_unwind(AssertUnwindSafe({
            let drops = drops.clone();
            move || {
                let _owner = MaybeUnpinned::new(DropProbe::new(drops));
                panic!("stage panicked before ownership transfer");
            }
        }));

        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn panicking_inner_destructor_is_not_run_twice() {
        let drops = Arc::new(AtomicUsize::new(0));
        let result = catch_unwind(AssertUnwindSafe({
            let drops = drops.clone();
            move || drop(MaybeUnpinned::new(DropProbe::panicking(drops)))
        }));

        assert!(result.is_err());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn pending_async_borrow_cancellation_drops_the_armed_owner() {
        let drops = Arc::new(AtomicUsize::new(0));
        let computation = Async::borrow(
            MaybeUnpinned::new(DropProbe::new(drops.clone())),
            scope_fn::<Async, MaybeUnpinned<DropProbe>, _>(move |mut token| {
                let _ = unsafe { token.as_mut() };
                <core::future::Pending<()> as Colorize<Async>>::colorize(core::future::pending())
            }),
        );
        {
            let mut future = core::pin::pin!(computation.async_());
            assert!(matches!(poll_once(future.as_mut()), Poll::Pending));
        }

        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn completed_async_borrow_drops_the_armed_owner() {
        let drops = Arc::new(AtomicUsize::new(0));
        let computation = Async::borrow(
            MaybeUnpinned::new(DropProbe::new(drops.clone())),
            scope_fn::<Async, MaybeUnpinned<DropProbe>, _>(|mut token| {
                let _ = unsafe { token.as_mut() };
                Async::ready(())
            }),
        );

        assert_eq!(block_on_test(computation.async_()), ());
        assert_eq!(drops.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn test_borrow_mut_reborrow_end() {
        let a = String::from("hello");
        borrow_mut!(a);
        reborrow!(a).push_str(" world");
        end_borrow_mut!(a);
        assert_eq!(a, "hello world");
    }

    #[test]
    fn test_borrow_inert_macros() {
        let a = String::from("inert");
        borrow_mut_inert!(a);
        let b = reborrow_inert!(a);
        end_borrow_mut_inert!(b);
        assert_eq!(b, "inert");
    }

    #[test]
    fn test_pin_inert_macro() {
        let mut a = String::from("pinned");
        pin_local!(a);
        a.push_str("_mut");
        assert_eq!(*a, "pinned_mut");
    }
}
